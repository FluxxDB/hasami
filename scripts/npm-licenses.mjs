// Writes THIRD_PARTY_LICENSES_NPM.md: every npm package whose code ends up in the
// built frontend, with its license text. It runs a real Vite build (into a temp
// folder, so dist/ is left alone) and records which node_modules files Rollup kept.
//
// Usage (from the repo root): node scripts/npm-licenses.mjs
import { build } from 'vite';
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const outFile = join(root, 'THIRD_PARTY_LICENSES_NPM.md');
const nm = `${sep}node_modules${sep}`;

/** "C:\repo\node_modules\@scope\name\dist\x.js" -> "C:\repo\node_modules\@scope\name" */
function packageDir(file) {
  const i = file.lastIndexOf(nm);
  if (i < 0) return null;
  const rest = file.slice(i + nm.length).split(sep);
  const n = rest[0].startsWith('@') ? 2 : 1;
  return file.slice(0, i + nm.length) + rest.slice(0, n).join(sep);
}

const dirs = new Set();
const outDir = mkdtempSync(join(tmpdir(), 'hasami-licenses-'));
try {
  await build({
    root,
    logLevel: 'warn',
    build: { outDir, emptyOutDir: true },
    plugins: [
      {
        name: 'collect-bundled-packages',
        generateBundle(_, bundle) {
          for (const chunk of Object.values(bundle)) {
            if (chunk.type !== 'chunk') continue;
            for (const [id, info] of Object.entries(chunk.modules)) {
              if (info.renderedLength === 0) continue; // tree-shaken away
              const file = id.replace(/^\0/, '').split('?')[0].replaceAll('/', sep);
              const dir = packageDir(file);
              if (dir) dirs.add(dir);
            }
          }
        },
      },
    ],
  });
} finally {
  rmSync(outDir, { recursive: true, force: true });
}

const packages = [...dirs]
  .map((dir) => {
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    const licenseFiles = readdirSync(dir)
      .filter((f) => /^(licen[sc]e|copying|notice)/i.test(f))
      .sort();
    const text = licenseFiles.map((f) => readFileSync(join(dir, f), 'utf8').replace(/^(\s*\n)+/, '').trimEnd()).join('\n\n');
    return { name: pkg.name, version: pkg.version, license: pkg.license ?? 'UNKNOWN', text };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const lines = [
  '# Third-party licenses: npm packages',
  '',
  'The npm packages whose code is bundled into the Hasami UI, with their license texts.',
  'Generated by `scripts/licenses.ps1` (`node scripts/npm-licenses.mjs`); do not edit by hand.',
  '',
  ...packages.map((p) => `- ${p.name} ${p.version}: ${p.license}`),
  '',
];
for (const p of packages) {
  lines.push(`## ${p.name} ${p.version}`, '', `License: ${p.license}`, '', '```text');
  lines.push(p.text || `No license file is included in the package; it declares ${p.license}.`);
  lines.push('```', '');
}
writeFileSync(outFile, lines.join('\n'));
console.log(`Wrote ${outFile} (${packages.length} packages)`);
